SELECT *
  FROM(
        SELECT CLASS_NO 과목번호, CLASS_NAME 과목이름, COUNT(*) "누적수강생수(명)"
          FROM TB_CLASS
          JOIN TB_GRADE USING (CLASS_NO)
         WHERE SUBSTR(TERM_NO, 1, 4) BETWEEN EXTRACT(YEAR FROM SYSDATE) AND EXTRACT(YEAR FROM SYSDATE) - 3 
         GROUP BY CLASS_NO, CLASS_NAME
         ORDER BY COUNT(*) DESC
  )
 WHERE ROWNUM <= 3;
