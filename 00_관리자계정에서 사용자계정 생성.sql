/*
    * 데이터베이스에는 "계정" 이라는 개념이 있음
    > 이 계정을 여러개 만들 수 있으며, 각 계정마다 필요한 권한을 부여할 수 있다.
    > 오라클 DBMS 설치 시 기본적으로 계정이 하나 만들어서 주어짐!! (sys as sysdba)
      설치 시 비밀번호는 우리가 직접 설정했었음!! (oracle)
    > 기본적으로 만들어주는 계정 == 기본 제공 "관리자" 계정 (dba - administractor, 관리자)
    > 관리자 계정에서는 모든 권한이 다 부여되어있다!! (즉, 관리자 계정으로 모든 일을 다 할 수 있음)
      (보안 상 관리자 계정에서 모든 작업을 하는 걸 권장하지 않음)
      
    * 그래서 우리는 일반 사용자 계정을 생성 후 기기에서만 쭉 작업 예정!!
    1. 우선 관리자 계정으로 접속
    2. 관리자 계정에서 일반 사용자 계정을 생성
    3. 관리자 계정에서 그 만들어진 일반 사용자 계정에 최소한의 권한 부여
    4. 그 일반 사용자 계정으로 접속해서 작업 진행!!
*/

-- 일반 사용자 계정을 만들 수 있는 권한은 "관리자 계정" 한테 있음!!
-- 계정을 생성하는 방법
-- [ 표현법 ]
-- CREATE USER 계정명 IDENTIFIED BY 비밀번호;

CREATE USER KH IDENTIFIED BY KH;
--> User KH이(가) 생성되었습니다.(인터프린터 방식)

-- 계정을 생성했다고 해서 바로 사용할 수 있는 것은 아님!!
-- 생성된 사용자 계정에게 최소한의 권한 (접속, 데이터 관리) 부여
-- 마찬가지로 권한을 부여할 수 있는 권한은 "관리자 계정" 한테 있음!!
-- [ 표현법 ]
-- GRANT 권한명1, 권한명2, .. TO 계정명;

-- 접속할 수 있는 권한 (롤) : CONNECT
-- 데이터 관리용 권한 (롤) : RESOURCE

GRANT CONNECT, RESOURCE TO KH;
--> Grant을(를) 성공했습니다.

-- 이 시점 부터 우리는 KH 계정에 접속해서 이것 저것 건들여 볼 수 있게됨!!

--------------------------------------------------------------------------------

-- 춘대학 문제 풀이를 위한 환경설정
-- CNS / CNS
CREATE USER CNS IDENTIFIED BY CNS;

-- 권한 부여
GRANT CONNECT, RESOURCE TO CNS;

--------------------------------------------------------------------------------

-- DDL(CREATE) 공부를 위한 환경설정
-- DDL / DDL
CREATE USER DDL IDENTIFIED BY DDL;

-- 권한 부여
GRANT CONNECT, RESOURCE TO DDL;